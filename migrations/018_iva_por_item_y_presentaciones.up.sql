-- IVA por ítem (regla 2.1) y presentaciones de compra (regla 2.2).
-- Idempotente: puede ejecutarse más de una vez sin perder datos nuevos.
BEGIN;

-- ---------------------------------------------------------------------------
-- 2.1) IVA por línea
-- ---------------------------------------------------------------------------

-- iva_incluido pasa a ser un dato DERIVADO de las líneas (puede ser NULL
-- cuando la factura mezcla modos). La columna se conserva por compatibilidad.
ALTER TABLE tb_compras
  ALTER COLUMN iva_incluido DROP NOT NULL;

ALTER TABLE tb_detallecompra
  ADD COLUMN IF NOT EXISTS modo_iva VARCHAR(10) NOT NULL DEFAULT 'incluido';

ALTER TABLE tb_detallecompra
  DROP CONSTRAINT IF EXISTS ck_dcompra_modo_iva;
ALTER TABLE tb_detallecompra
  ADD CONSTRAINT ck_dcompra_modo_iva
  CHECK (modo_iva IN ('incluido', 'mas_iva', 'exento'));

-- Backfill de las líneas históricas: antes solo existía el IVA global.
-- 'exento' donde la tarifa era 0; 'mas_iva' donde el global era false.
-- Las líneas ya migradas con modo explícito no se tocan.
UPDATE tb_detallecompra d
   SET modo_iva = CASE WHEN d.iva = 0 THEN 'exento' ELSE 'mas_iva' END
  FROM tb_compras c
 WHERE c.id_compra = d.id_compra
   AND d.modo_iva = 'incluido'
   AND (c.iva_incluido = FALSE OR d.iva = 0);

-- Las órdenes de compra siempre calcularon con IVA incluido: el valor por
-- defecto 'incluido' ya es correcto para las líneas históricas.
ALTER TABLE tb_detalleordencompra
  ADD COLUMN IF NOT EXISTS modo_iva VARCHAR(10) NOT NULL DEFAULT 'incluido';

ALTER TABLE tb_detalleordencompra
  DROP CONSTRAINT IF EXISTS ck_dorcompra_modo_iva;
ALTER TABLE tb_detalleordencompra
  ADD CONSTRAINT ck_dorcompra_modo_iva
  CHECK (modo_iva IN ('incluido', 'mas_iva', 'exento'));

-- ---------------------------------------------------------------------------
-- 2.2) Unidad base por línea (comparar compras y recepciones en la unidad
--      real de inventario: "1 paca de arroz = 20 kg")
-- ---------------------------------------------------------------------------

ALTER TABLE tb_detallecompra
  ADD COLUMN IF NOT EXISTS unidades_base NUMERIC(14, 4);
ALTER TABLE tb_detallecompra
  ADD COLUMN IF NOT EXISTS unidad_base VARCHAR(20);
ALTER TABLE tb_detallecompra
  DROP CONSTRAINT IF EXISTS ck_dcompra_unidades_base;
ALTER TABLE tb_detallecompra
  ADD CONSTRAINT ck_dcompra_unidades_base
  CHECK (unidades_base IS NULL OR unidades_base > 0);

ALTER TABLE tb_detalleordencompra
  ADD COLUMN IF NOT EXISTS unidades_base NUMERIC(14, 4);
ALTER TABLE tb_detalleordencompra
  ADD COLUMN IF NOT EXISTS unidad_base VARCHAR(20);
ALTER TABLE tb_detalleordencompra
  DROP CONSTRAINT IF EXISTS ck_dorcompra_unidades_base;
ALTER TABLE tb_detalleordencompra
  ADD CONSTRAINT ck_dorcompra_unidades_base
  CHECK (unidades_base IS NULL OR unidades_base > 0);

-- Backfill de las líneas históricas: la conversión directa (misma unidad,
-- kg<->g, lt<->ml) se conoce; las presentaciones antiguas no tienen factor
-- configurado y quedan en NULL (la anulación usa entonces la conversión
-- histórica, igual que antes de esta migración).
UPDATE tb_detallecompra d
   SET unidad_base = i.unidad_medida,
       unidades_base = CASE
         WHEN LOWER(d.medida) = LOWER(i.unidad_medida) THEN d.cantidad
         WHEN LOWER(d.medida) = 'g'  AND LOWER(i.unidad_medida) = 'kg' THEN d.cantidad / 1000
         WHEN LOWER(d.medida) = 'kg' AND LOWER(i.unidad_medida) = 'g'  THEN d.cantidad * 1000
         WHEN LOWER(d.medida) = 'ml' AND LOWER(i.unidad_medida) = 'lt' THEN d.cantidad / 1000
         WHEN LOWER(d.medida) = 'lt' AND LOWER(i.unidad_medida) = 'ml' THEN d.cantidad * 1000
         ELSE NULL
       END
  FROM tb_insumo i
 WHERE d.id_insumo = i.id_insumo
   AND d.unidades_base IS NULL;

UPDATE tb_detalleordencompra d
   SET unidad_base = i.unidad_medida,
       unidades_base = CASE
         WHEN LOWER(d.medida) = LOWER(i.unidad_medida) THEN d.cantidad
         WHEN LOWER(d.medida) = 'g'  AND LOWER(i.unidad_medida) = 'kg' THEN d.cantidad / 1000
         WHEN LOWER(d.medida) = 'kg' AND LOWER(i.unidad_medida) = 'g'  THEN d.cantidad * 1000
         WHEN LOWER(d.medida) = 'ml' AND LOWER(i.unidad_medida) = 'lt' THEN d.cantidad / 1000
         WHEN LOWER(d.medida) = 'lt' AND LOWER(i.unidad_medida) = 'ml' THEN d.cantidad * 1000
         ELSE NULL
       END
  FROM tb_insumo i
 WHERE d.id_insumo = i.id_insumo
   AND d.unidades_base IS NULL;

-- ---------------------------------------------------------------------------
-- 2.2) Presentaciones de compra por insumo ("1 paca = 20 kg")
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS tb_insumo_presentacion (
  id_presentacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_insumo INTEGER NOT NULL,
  presentacion VARCHAR(10) NOT NULL,
  unidades_base NUMERIC(14, 4) NOT NULL,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_insumo_presentacion_insumo
    FOREIGN KEY (id_insumo) REFERENCES tb_insumo (id_insumo) ON DELETE CASCADE,
  CONSTRAINT ck_insumo_presentacion_nombre
    CHECK (presentacion IN ('paq', 'paca', 'caja', 'bolsa', 'sixpack')),
  CONSTRAINT ck_insumo_presentacion_unidades
    CHECK (unidades_base > 0),
  CONSTRAINT uq_insumo_presentacion
    UNIQUE (id_insumo, presentacion)
);

COMMIT;
